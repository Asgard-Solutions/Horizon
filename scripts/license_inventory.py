"""Offline license inventory of every Python wheel (vendor/wheels) and every Node package (frontend/node_modules + yarn.lock).

Usage: python scripts/license_inventory.py   -> writes docs/licenses/INVENTORY.md, exits 1 if a runtime dependency is not permissive.
"""
import email.parser
import json
import re
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PERMISSIVE = {"MIT", "ISC", "BSD-2-CLAUSE", "BSD-3-CLAUSE", "APACHE-2.0", "0BSD", "PSF-2.0", "PYTHON-2.0", "OFL-1.1",
              "CC0-1.0", "UNLICENSE", "BLUEOAK-1.0.0", "ZLIB", "CC-BY-4.0"}
WEAK_COPYLEFT = {"MPL-2.0", "LGPL-2.1", "LGPL-3.0", "EPL-2.0"}
ALIASES = {"MIT LICENSE": "MIT", "BSD LICENSE": "BSD-3-CLAUSE", "BSD": "BSD-3-CLAUSE", "APACHE SOFTWARE LICENSE": "APACHE-2.0",
           "APACHE 2.0": "APACHE-2.0", "MOZILLA PUBLIC LICENSE 2.0 (MPL 2.0)": "MPL-2.0", "PYTHON SOFTWARE FOUNDATION LICENSE": "PSF-2.0",
           "SIL OPEN FONT LICENSE 1.1": "OFL-1.1"}
CLASSIFIER = {"MIT License": "MIT", "BSD License": "BSD-3-CLAUSE", "Apache Software License": "APACHE-2.0",
              "Mozilla Public License 2.0 (MPL 2.0)": "MPL-2.0", "Python Software Foundation License": "PSF-2.0"}
PY_RUNTIME = {"fastapi", "starlette", "uvicorn", "pydantic", "pydantic-core", "anyio", "h11", "click", "colorama", "idna",
              "annotated-types", "typing-extensions", "typing-inspection", "sniffio"}


def verdict(expr: str) -> str:
    parts = [ALIASES.get(p.strip().upper(), p.strip().upper()) for p in re.split(r"\s+OR\s+|/", expr.strip("() ")) if p.strip()]
    if not parts or parts == ["UNKNOWN"]:
        return "FLAG: unknown"
    if any(p in PERMISSIVE for p in parts):
        return "OK"
    if any(p in WEAK_COPYLEFT for p in parts):
        return "REVIEW: weak copyleft"
    return "FLAG"


def python_wheels():
    rows = {}
    for whl in sorted((ROOT / "vendor" / "wheels").glob("*.whl")):
        with zipfile.ZipFile(whl) as zf:
            meta_name = next(n for n in zf.namelist() if n.endswith(".dist-info/METADATA"))
            msg = email.parser.Parser().parsestr(zf.read(meta_name).decode("utf-8", "replace"))
        name = msg["Name"].lower().replace("_", "-")
        lic = msg.get("License-Expression") or ""
        if not lic:
            classifiers = [c.split(" :: ")[-1] for c in msg.get_all("Classifier") or [] if c.startswith("License ::")]
            lic = " OR ".join(CLASSIFIER.get(c, c) for c in classifiers) or (msg.get("License") or "UNKNOWN").splitlines()[0][:40]
        scope = "runtime" if name in PY_RUNTIME else "test"
        rows[(name, msg["Version"])] = (lic, scope, whl.name)
    return rows


def node_packages():
    nm = ROOT / "frontend" / "node_modules"
    pkgs = {}
    for pj in nm.glob("**/package.json"):
        rel = pj.relative_to(nm).parts
        if "node_modules" in rel[:-1] and rel[-2] != rel[-2]:
            continue
        try:
            data = json.loads(pj.read_text(encoding="utf-8"))
        except (ValueError, OSError):
            continue
        if not data.get("name") or not data.get("version") or pj.parent.name not in data["name"].split("/")[-1:]:
            continue
        lic = data.get("license") or (data.get("licenses") or [{}])[0].get("type", "UNKNOWN")
        pkgs[data["name"]] = {"version": data["version"], "license": lic if isinstance(lic, str) else lic.get("type"),
                              "deps": list((data.get("dependencies") or {}).keys())}
    root = json.loads((ROOT / "frontend" / "package.json").read_text(encoding="utf-8"))
    runtime, stack = set(), list(root.get("dependencies", {}))
    while stack:
        n = stack.pop()
        if n in runtime or n not in pkgs:
            continue
        runtime.add(n)
        stack.extend(pkgs[n]["deps"])
    locked = set(re.findall(r'^"?(@?[^@\s"]+)@', (ROOT / "frontend" / "yarn.lock").read_text(encoding="utf-8"), re.M))
    missing = sorted(locked - set(pkgs))
    return pkgs, runtime, missing


def main():
    out = ["# License inventory (generated by `scripts/license_inventory.py`)", "",
           "Verdicts: OK = permissive; REVIEW = weak copyleft (allowed for build/test tools that are not shipped); FLAG = not acceptable / unknown.", ""]
    bad = []
    out += ["## Python packages (exact wheels bundled in `vendor/wheels` for Windows x64)", "",
            "| Package | Version | License | Scope | Verdict |", "|---|---|---|---|---|"]
    for (name, ver), (lic, scope, _) in sorted(python_wheels().items()):
        v = verdict(lic)
        if v != "OK" and scope == "runtime":
            bad.append(f"python {name}")
        out.append(f"| {name} | {ver} | {lic} | {scope} | {v} |")
    pkgs, runtime, missing = node_packages()
    out += ["", "## Node packages (`frontend/node_modules`)", "",
            "Scope *runtime* = compiled into `frontend/dist` (shipped). Everything else is a build tool (not shipped).", "",
            "| Package | Version | License | Scope | Verdict |", "|---|---|---|---|---|"]
    for name in sorted(pkgs):
        p = pkgs[name]
        scope = "runtime" if name in runtime else "build"
        v = verdict(p["license"])
        if v != "OK" and scope == "runtime":
            bad.append(f"node {name}")
        out.append(f"| {name} | {p['version']} | {p['license']} | {scope} | {v} |")
    if missing:
        out += ["", "### In yarn.lock but not installed on this OS (platform-specific optional build binaries)", "",
                "These are the Windows/macOS variants of packages listed above (same project, same license); they are build-only.", ""]
        out += [f"- {m}" for m in missing]
    out += ["", f"**Runtime dependencies needing attention: {', '.join(bad) if bad else 'none'}**", ""]
    target = ROOT / "docs" / "licenses" / "INVENTORY.md"
    target.write_text("\n".join(out), encoding="utf-8")
    print(f"Wrote {target}: {len(pkgs)} node packages ({len(runtime)} runtime), python wheels listed. Problems: {bad or 'none'}")
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
